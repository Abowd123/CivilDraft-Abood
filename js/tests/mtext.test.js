/* ═══ النصُّ بفقرة ═══ §٣/١٤
   `نصّ` سطرٌ واحد، و`eText` في DXF يسحق `\n` إلى مسافة — فالملاحظاتُ
   العامةُ على الورقة (وهي فقراتٌ دائماً) كانت تُكتَب سطراً سطراً
   بالأيدي، وكلُّ تعديلٍ يُعيد ترتيبَها كلَّها.
   والقرارُ المعماريُّ الذي يُقاس هنا: **اللفُّ يُحسَب عند الرسم لا عند
   الحفظ**، فتغييرُ العرضِ أو الحجمِ يُعيد اللفَّ من تلقائه ولا يُخزَّن
   ناتجٌ يتعارض مع مصدره. والمخرَجُ أسطرُ `text` عاديةٌ فكلُّ مصدِّرٍ
   يعرفها سلفاً.
   التشغيل:  node js/tests/mtext.test.js                             */
import {shim,group,groupAsync,ok,eq,near,deep,summary} from "./harness.js";
shim();
const {S,newState,ensureShape,clearHistory,edit,undo,txtH,shapeNotes}=
 await import("../core/state.js");
const D =await import("../core/dims.js");
const EN=await import("../core/ents.js");

const reset=()=>{newState(); ensureShape(); clearHistory()};
const mk=(txt,wid,hm,al)=>{
 let a=null;
 edit(()=>{a=D.addMText([0,0],txt,wid,hm,al)},"فقرة");
 return a;
};
const LONG="جميع الأبعاد بالمليمتر ما لم يُذكر خلاف ذلك والمناسيب "
 +"من منسوب الدور الأرضي النهائي";

group("الثوابتُ معلَنةٌ ومصدَّرة",()=>{
 ok(D.MT_ADV>0&&D.MT_ADV<1,"عرضُ المحرف نسبةٌ من الارتفاع");
 ok(D.MT_LEAD>1,"وتباعدُ الأسطر أكبرُ من الارتفاع فلا تتلاصق");
 ok(D.MT_WMIN>0&&D.MT_WMAX>D.MT_WMIN,"وحدّا العرضِ معقولان");
});

group("اللفُّ: كلماتٌ لا محارف",()=>{
 const h=200;
 const L=D.mtWrap("واحد اثنان ثلاثة أربعة خمسة ستة سبعة",1200,h);
 ok(L.length>1,"النصُّ الطويلُ يُلَفّ");
 L.forEach(x=>ok(!/^\s|\s$/.test(x),`«${x}» بلا مسافاتٍ طرفية`));
 /* ولا كلمةَ تُقطَع: كلُّ كلمةٍ في الأصل موجودةٌ كاملةً في سطرٍ ما */
 const words="واحد اثنان ثلاثة أربعة خمسة ستة سبعة".split(" ");
 const all=L.join(" ").split(/\s+/);
 deep(all,words,"وكلُّ الكلماتِ باقيةٌ بترتيبها بلا قطع");
});

group("`\\n` معنًى لا زينة",()=>{
 const L=D.mtWrap("ملاحظات عامة\nالبند الأول\nالبند الثاني",100000,200);
 eq(L.length,3,"ثلاثةُ أسطرٍ صريحةٍ تبقى ثلاثة ولو وسع العمود");
 eq(L[0],"ملاحظات عامة","الأوّل");
 eq(L[2],"البند الثاني","والثالث");
 /* وسطرٌ فارغٌ يبقى فاصلاً بين فقرتين */
 eq(D.mtWrap("أ\n\nب",100000,200).length,3,"والسطرُ الفارغُ يبقى فاصلاً");
});

group("الكلمةُ الأطولُ من العمود تبقى سطراً ولا تُقطَع",()=>{
 const w="كلمةٌطويلةٌجداًلاتُقطَع";
 const L=D.mtWrap(w,200,200);
 eq(L.length,1,"سطرٌ واحد");
 eq(L[0],w,"والكلمةُ كاملةٌ — قطعُ كلمةٍ عربيةٍ يفسد شكلَها");
});

group("حالاتٌ حدّيةٌ لا ترمي",()=>{
 deep(D.mtWrap("",3000,200),[""],"نصٌّ فارغٌ ⇒ سطرٌ فارغ");
 deep(D.mtWrap(null,3000,200),[""],"وnull كذلك");
 ok(D.mtWrap("أ ب ج",0,200).length>=1,"وعرضُ صفرٍ لا يرمي");
 ok(D.mtWrap("أ ب ج",3000,0).length>=1,"وارتفاعُ صفرٍ كذلك");
});

group("الكيانُ يُنشَأ ويُطبَّع",()=>{
 reset();
 const a=mk(LONG,4000,1);
 eq(a.kind,"mtext","نوعٌ ثالثٌ في anno — لا كيانٌ جديدٌ ولا مجموعة");
 eq(a.wid,4000,"والعرضُ محفوظ");
 eq(a.al,"ar","والمحاذاةُ إلى اليمين افتراضاً — النصُّ عربيّ");
 eq(S.anno.length,1,"في مجموعةِ التأشير نفسها");
 /* عرضٌ خارجَ الحدِّ يُقصَر ولا يُسقِط النصَّ */
 reset();
 const b=mk("أ ب",5,1);
 eq(b.wid,D.MT_WMIN,"عرضٌ دون الحدِّ يُرفَع إليه");
 reset();
 let e="";
 try{edit(()=>{D.addMText([0,0],"   ",3000,1)},"x")}catch(x){e=x.message}
 eq(S.anno.length,0,"ونصٌّ فارغٌ لا يُنشَأ");
});

group("التطبيعُ يُصلِح عرضاً فاسداً ويُسجِّله",()=>{
 reset();
 mk(LONG,4000,1);
 S.anno[0].wid=-99;
 ensureShape();
 eq(S.anno.length,1,"الفقرةُ لم تُسقَط");
 ok(S.anno[0].wid>=D.MT_WMIN,"وعرضُها أُعيد إلى حدّه");
 /* السجلُّ يُجمِع التقويماتَ بنوعها ويذكر مثالاً — فالبحثُ عن
    الحقلِ واسمِ النوعِ لا عن نصِّ الرسالةِ الكامل */
 const NT=JSON.stringify(shapeNotes());
 ok(/wid/.test(NT)&&/تأشير/.test(NT),
  `والإصلاحُ مكتوبٌ لا صامت: ${NT.slice(0,120)}`);
});

group("اللفُّ يُحسَب عند الرسم لا عند الحفظ",()=>{
 reset();
 const a=mk(LONG,2000,1);
 const n1=D.mtLines(a).length;
 ok(n1>1,"عمودٌ ضيّقٌ ⇒ أسطرٌ كثيرة");
 /* لا حقلَ أسطرٍ مخزَّن: العرضُ وحدَه يتغيّر فيُعاد اللفّ */
 ok(!("lines" in a),"ولا حقلَ أسطرٍ مخزَّنٌ يتعارض مع مصدره");
 edit(()=>{a.wid=100000},"وسّع");
 const n2=D.mtLines(a).length;
 ok(n2<n1,`توسيعُ العمود يُقلّل الأسطر (${n1} ⇒ ${n2})`);
 eq(a.s.indexOf("\n")<0,true,"والنصُّ المخزَّنُ لم يُمَسّ");
 /* والحجمُ كذلك: حرفٌ أكبرُ ⇒ أسطرٌ أكثر */
 edit(()=>{a.wid=2000; a.hm=2},"كبّر");
 ok(D.mtLines(a).length>=n1,"وتكبيرُ الحرفِ يزيدها");
});

group("المخرَجُ أسطرُ نصٍّ عاديةٌ ينزل بعضُها تحت بعض",()=>{
 reset();
 const a=mk(LONG,3000,1);
 const P=D.annoPrims(a);
 const lines=D.mtLines(a);
 eq(P.length,lines.length,"أوّليةٌ لكلِّ سطر");
 ok(P.every(g=>g.t==="text"),
  "وكلُّها نصٌّ عاديّ — فكلُّ مصدِّرٍ يعرفها بلا تعديل");
 ok(P.every(g=>g.L==="A-ANNO"),"وعلى طبقةِ التأشير");
 /* تنزل: كلُّ سطرٍ أوطأُ من سابقه بخطوةٍ واحدة */
 for(let i=1;i<P.length;i++)
  ok(P[i].y<P[i-1].y,`السطر ${i+1} أوطأُ من سابقه`);
 const step=P.length>1?(P[0].y-P[1].y):0;
 if(P.length>2)near(P[1].y-P[2].y,step,1,"والخطوةُ ثابتة");
 /* ومحاذاةٌ إلى اليمين تُعلَن بـbr — وهي مدعومةٌ في المصدِّرات كلِّها */
 eq(P[0].al,"br","يمينٌ للعربيّ");
 reset();
 const b=mk(LONG,3000,1,"bl");
 eq(D.annoPrims(b)[0].al,"bl","ويسارٌ لمن اختاره");
});

group("الصندوقُ حقيقيٌّ فالفهرسُ يراها والنقرةُ تصيبها",()=>{
 reset();
 const a=mk(LONG,4000,1);
 const b=D.mtBox(a);
 eq(b.x0,0,"يبدأ من المرساة");
 eq(b.x1,4000,"ويمتدُّ عرضَ العمود");
 ok(b.y1===0&&b.y0<0,"والنصُّ ينزل من المرساة");
 const n=D.mtLines(a).length;
 near(b.y1-b.y0, txtH()*D.MT_LEAD*n, 1,"والارتفاعُ أسطرٌ مضروبةٌ بالتباعد");
 /* نقرةٌ في وسط الفقرة تصيبها — لا على مرساتها وحدها */
 const h=EN.hitTest(2000,(b.y0+b.y1)/2,150);
 ok(h&&h.k==="anno"&&h.id===a.id,"نقرةٌ في وسطها تصيبها");
 /* وخارجَها لا */
 ok(!EN.hitTest(40000,0,150),"وبعيداً عنها لا شيء");
});

group("مقبضُ العرضِ يُعيد اللفَّ لحظةَ السحب",()=>{
 reset();
 const a=mk(LONG,6000,1);
 const g=EN.gripsOf({k:"anno",id:a.id});
 eq(g.length,2,"مقبضانِ: الموضعُ والعرض");
 ok(g.some(x=>x.k==="w"),"ومقبضُ العرضِ معلَن");
 const n0=D.mtLines(a).length;
 /* العقد: dragGrip(g,o,p) حيث g يحمل الكيانَ في g.s — لا (o,g,p) */
 const o=EN.grabOf({k:"anno",id:a.id});
 const gw=g.find(x=>x.k==="w");
 edit(()=>{EN.dragGrip({s:{k:"anno",id:a.id},k:gw.k},o,[1500,0])},"سحب");
 ok(D.mtLines(a).length>n0,"سحبُ العرضِ إلى الداخلِ يزيد الأسطر");
});

group("التراجعُ خطوةٌ واحدة",()=>{
 reset();
 mk(LONG,3000,1);
 eq(S.anno.length,1,"أُنشِئت");
 undo();
 eq(S.anno.length,0,"والتراجعُ يُزيلها");
});

process.exit(summary()?1:0);
