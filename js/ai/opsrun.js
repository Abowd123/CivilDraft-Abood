/* ═══ تنفيذ عمليات المزوّد ═══
   applyOps مُصدَّقةٌ ذاتياً (validate قبل أي كتابة) لكنها لا تفتح
   خطوةَ تراجعٍ بنفسها بقصد — العقدُ معلَنٌ في رأس ops.js:
   الاستدعاء edit(()=>applyOps(list)). فهذا هو اللافّ الوحيد لذلك
   العقد، ولا مكان آخر ينادي applyOps مباشرة خارج الاختبار.

   لا معاينةَ هنا كما في ai/run.js (trial→commit/rollback): مفردات
   ops محدودةٌ بقصد ولا تحوي نقلاً ولا حذفاً ولا دوراناً — إنشاءٌ
   وتسميةُ حقولٍ فقط — فخطوةٌ ذرّيةٌ واحدة تكفي، وedit() نفسه
   يرجع تلقائياً إن رمى fn() استثناءً. */
import {edit,editFailed} from "../core/state.js";
import {applyOps} from "./ops.js";

/* list بالمتر خامٌّ كما جاء من المزوّد أو من بنّاء الكتل — لا مخرَج
   validate().ok (بالمليمتر)، فـapplyOps تُصدِّق وتحوّل بنفسها.
   opt.atomic=1 ⇒ كلٌّ أو لا شيء (راجع ops.js).
   يُنادى بعد أن يوافق المستخدم على المعاينة (validate بلا كتابة) —
   فلا شيء يُثبَّت بلا نقرة، ولو لم تكن هناك لقطةٌ حيّةٌ على اللوحة
   كما في مسار الخطّة. */
export function runOps(list,opt){
 return edit(()=>applyOps(list,opt));
}

/* ═══ معاملةٌ ذرّية من دفعاتٍ متتابعة ═══
   الكتلةُ التي فيها بابٌ لا تُبنى دفعةً واحدة: معرّفُ الجدار الذي
   يُفتَح عليه الباب لا يُعرَف إلا بعد إدراج الجدار. فتُدرَج الدفعتان
   في edit() واحدة: fn تستلم apply(list) (= applyOps ذرّية — أيُّ رفضٍ
   يرمي) وتستطيع قراءةَ نتيجة الأولى لبناء الثانية. فشلُ أيٍّ منهما
   يرمي فيُعيد edit() الحالةَ كلَّها — لا جدرانَ بلا باب (بند 80/104)،
   وخطوةُ تراجعٍ واحدة عند النجاح.
   fn تعيد كائناً (لا undefined). تعيد: {ok:1,out} أو {ok:0,error}
   — السببُ يُحفَظ هنا لأن edit() لا يُعيد الاستثناء لمن نادى. */
export function runAtomic(label,fn){
 let why="";
 const out=edit(()=>{
  try{return fn(list=>applyOps(list,{atomic:1}))}
  catch(e){why=(e&&e.message)||String(e); throw e}
 },label);
 if(out===undefined||editFailed())
  return {ok:0,error:why||"تعذّر التنفيذ"};
 return {ok:1,out};
}
