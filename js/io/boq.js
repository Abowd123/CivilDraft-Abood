/* ═══ تصدير جدول الكميات — CSV ═══
   نصٌّ صريح يفتحه أي جدولٍ حسابيّ، وأصدقُ ما يُصدَّر إليه رقمٌ
   يُجمَع لا نصٌّ يُقرَأ. فالأرقام تخرج بالنقطة العشرية لا بالفاصلة
   العربية: Excel وLibreOffice يقرآن «12.34» رقماً و«١٢٫٣٤» نصّاً
   لا يُجمَع — والعناوين عربيةٌ لأنها تُقرَأ، والقيَم إنجليزيةٌ
   لأنها تُحسَب.

   والفاصلُ فاصلةٌ لا منقوطة: RFC 4180 هو العقد، والحقلُ الذي
   يحوي فاصلةً يُقتبَس. ولا تُبدَّل بمنقوطةٍ إرضاءً لإعدادٍ محلّيّ
   في نسخةٍ واحدة من برنامجٍ واحد — فالملفّ يُقرَأ في مكانٍ لا
   نعرفه.

   وBOM في أوّل الملفّ: بدونه يقرأ Excel على ويندوز العربيةَ
   بترميزٍ محلّيّ فتخرج رموزاً. محرفٌ واحد يمنع عطباً لا يُشخَّص.

   والوحدات في العنوان لا في الخليّة: «المساحة (م²)» ثم رقمٌ
   مجرَّد — لا «12.34 م²» فيصير الحقلُ نصّاً في كل صفٍّ من ألف. */
import {sqm,m2,m3} from "../core/units.js";

const BOM="\ufeff";
/* حقلُ CSV: يُقتبَس إن حوى فاصلةً أو اقتباساً أو سطراً — والاقتباس
   يُضاعَف داخل الاقتباس، وهو نصُّ المعيار لا اجتهاداً */
const Q=v=>{
 const s=String(v==null?"":v);
 return /[",\n\r]/.test(s) ? `"${s.replace(/"/g,'""')}"` : s;
};
const row=a=>a.map(Q).join(",");
/* الأرقام: المليمتر يخرج بوحدته المقروءة، بالنقطة لا بالفاصلة.
   وsqm وm2 وm3 يعيدون نصّاً بالنقطة سلفاً (toFixed) — فلا
   تحويلَ ثانٍ يفترق عنها. */
const A2=v=>sqm(v);          /* مم² → م² بمنزلتين */
const L2=v=>m2(v);           /* مم  → م  بمنزلتين */
const L3=v=>m3(v);           /* مم  → م  بثلاث    */
const V3=v=>((+v||0)/1e9).toFixed(3);   /* مم³ → م³ */

export function toCSV(B,opt){
 const O=Object.assign({sep:"\n"},opt||{});
 const L=[];
 const put=a=>L.push(row(a));
 const gap=()=>L.push("");

 /* ═══ الترويسة ═══ */
 put(["جدول الكميات",B.name]);
 if(B.tag)put(["المستوى",B.tag]);
 put(["المقياس",`1:${B.scale}`]);
 if(B.date)put(["التاريخ",B.date]);
 put(["ارتفاع الجدار (م)",L2(B.wallH)]);
 gap();

 /* ═══ المناطق ═══
    الملاحظة عمودٌ صريح: القديمةُ تُعَدّ ولا تُخفى، والمجموع
    يشملها — فهو صادقٌ عن الحالة كما هي لا كما يُرجى. */
 put(["المناطق"]);
 put(["المعرّف","الاسم","المساحة (م²)","المحيط (م)","الحالة","ملاحظة"]);
 B.areas.rows.forEach(r=>{
  put([r.id,r.name,A2(r.area),L2(r.perim),
   r.valid||(r.stale?"قديمة":"سليمة"),r.stale?"قديمة":""]);
 });
 put(["","المجموع",A2(B.areas.total),"",
  B.areas.stale?`${B.areas.stale} قديمة`:""]);
 gap();

 /* ═══ الفتحات ═══
    المدى يُذكَر بعمودَين لا بنصٍّ «900–1200»: عمودان يُفرَزان
    ويُجمَعان، والنصُّ يُقرَأ ولا يُحسَب. */
 put(["الفتحات"]);
 put(["النوع","العدد","أصغر عرض (م)","أكبر عرض (م)",
  "أصغر ارتفاع (م)","أكبر ارتفاع (م)","المساحة (م²)","المصاريع",
  "معطوبة"]);
 B.opens.rows.forEach(r=>{
  put([r.name,r.n,L2(r.wMin),L2(r.wMax),
   L2(r.hMin),L2(r.hMax),A2(r.ar),r.pan||"",r.bad||""]);
 });
 put(["المجموع",B.opens.total,"","","","",A2(B.opens.ar),"",
  B.opens.bad||""]);
 gap();

 /* ═══ الجدران ═══
    «سماكات» عمودٌ يقول إن كان «الأشيع» يخفي غيرَه: قيمةٌ أكبر
    من واحدٍ تعني أن الحجم تقديرٌ لا قياس. تُقال ولا تُصلَح. */
 put(["الجدران"]);
 put(["النوع","العدد","الطول (م)","السماكة الأشيع (م)","سماكات",
  "الارتفاع (م)","مساحة الوجه (م²)","الحجم (م³)","فتحات"]);
 B.walls.rows.forEach(r=>{
  put([r.name,r.n,L2(r.len),L3(r.t),r.tn,
   L2(r.h),A2(r.face),V3(r.vol),r.opens||""]);
 });
 put(["المجموع",B.walls.n,L2(B.walls.len),"","","",
  A2(B.walls.face),V3(B.walls.vol),""]);

 /* ═══ الأعمدة — المراجعة #5 ═══
    تُجمَع بالنوع والمادّة؛ لا حجمَ لها هنا (لا ارتفاعَ مخزَّناً
    للعمود كالجدار) — المساحة مقطعُها الأفقي فقط. */
 if(B.cols&&B.cols.n){
  gap();
  put(["الأعمدة"]);
  put(["النوع · المادّة","العدد","أصغر مقاس (م)","أكبر مقاس (م)",
   "المساحة (م²)"]);
  B.cols.rows.forEach(r=>{
   put([r.name,r.n,L2(r.wMin),L2(r.wMax),A2(r.area)]);
  });
  put(["المجموع",B.cols.n,"","",A2(B.cols.area)]);
 }
 /* ═══ الأدوات الصحية والمطبخية — المراجعة #5 ═══ */
 if(B.fixt&&B.fixt.n){
  gap();
  put(["الأدوات الصحية والمطبخية"]);
  put(["النوع","العدد"]);
  B.fixt.rows.forEach(r=>put([r.name,r.n]));
  put(["المجموع",B.fixt.n]);
 }
 /* ═══ الدرج — المراجعة #5 ═══
    سطرٌ لكل قِلعة: لا نوع يُجمَع به، وكلّ درجٍ قياساته الخاصّة —
    كخصائصه في props.js (stCheck نفسها). */
 if(B.stairs&&B.stairs.n){
  gap();
  put(["الدرج"]);
  put(["المعرّف","العرض (م)","عدد القوائم","طول القِلعة (م)","الحالة"]);
  B.stairs.rows.forEach(r=>{
   put([r.id,L2(r.w),r.n,L2(r.len),r.ok?"سليم":"خارج المدى المريح"]);
  });
  put(["المجموع",L2(B.stairs.len),"","",
   B.stairs.bad?`${B.stairs.bad} خارج المدى`:""]);
 }

 /* ═══ الجدران — تفصيليّ ═══ اختياريّ: يظهر فقط إن وُجد
    wallsDetail في B، فالمستدعي القديم (بلا هذا الحقل) لا ينكسر. */
 if(B.wallsDetail){
  gap();
  put(["الجدران — تفصيلي"]);
  put(["المعرّف","النوع","الطول (م)","السماكة (م)","الارتفاع (م)",
   "مساحة الوجه (م²)","الحجم (م³)","الحالة","عدد الفتحات"]);
  B.wallsDetail.forEach(r=>{
   put([r.id,r.name,L2(r.len),L3(r.t),L2(r.h),
    A2(r.face),V3(r.vol),r.state,r.opens]);
  });
 }
 /* ═══ الفتحات — تفصيليّ ═══ */
 if(B.opensDetail){
  gap();
  put(["الفتحات — تفصيلي"]);
  put(["المعرّف","النوع","العرض (م)","الارتفاع (م)","الجدار",
   "الموضع (م)","الحالة","صلاحية الطبقة"]);
  B.opensDetail.forEach(r=>{
   put([r.id,r.name,L2(r.w),L2(r.h),r.wall,L2(r.s),r.valid,r.layValid]);
  });
 }

 return {txt:BOM+L.join(O.sep)+O.sep,
  lines:L.length,
  notes:noteOf(B)};
}
/* ═══ الملاحظات ═══
   ما لا يقوله الجدولُ صراحةً يُقال هنا، فيبلغ لوحةَ الحالة —
   كما تفعل notes في io/svg.js. */
export function noteOf(B){
 const n=[];
 if(B.areas.stale)
  n.push(`${B.areas.stale} منطقةً قديمة دخلت المجموع — `
   +`حدّثها بأمر arearef قبل الاعتماد عليه`);
 B.walls.rows.forEach(r=>{
  if(r.tn>1)
   n.push(`${r.name}: ${r.tn} سماكات مختلفة — `
    +`الحجم محسوبٌ بالأشيع (${m3(r.t)} م)`);
 });
 if(B.opens.total)
  n.push("أطوال الجدران ومساحاتها لا تُطرَح منها الفتحات");
 /* ═══ الحالة (مرحلة ٤ · ٣) ═══ المعطوبة لا تُستبعَد — تُرسَم
    وتُصدَّر فعلاً فتخصمها من العدّ يكذب — لكنها تُقال هنا كما
    تُقال «القديمة» أعلاه، لا تختفي في رقمٍ صامت. */
 if(B.opens.bad)
  n.push(`${B.opens.bad} فتحةً معطوبة (تخرج عن مدى جدارها أو `
   +`تتراكب مع أخرى أو جدارها مفقود) دخلت العدّ — راجعها من لوحة `
   +`الحالة قبل الاعتماد على الجدول`);
 /* ═══ الدرج خارج المدى المريح — المراجعة #5 ═══
    كالفتحة المعطوبة: يدخل العدّ (يُرسَم ويُصدَّر فعلاً) ولا يُستبعَد،
    لكن يُقال صراحةً — لا فرقَ يُخفى عن قارئٍ يشتري قِلعةً. */
 if(B.stairs&&B.stairs.bad)
  n.push(`${B.stairs.bad} درجاً خارج المدى المريح (القائمة أو `
   +`النائمة أو قاعدة 2ق+ن أو العرض) دخل العدّ — راجعه من لوحة `
   +`الخصائص قبل الاعتماد على الجدول`);
 /* ═══ نطاق الجدول ═══ لا إسقاط صامت: المخفيّ والمرئيّ غير
    القابل للطباعة يُستبعَدان من BOQ (كما في التصدير)، وعددُهما
    يُقال هنا بدل أن يختفيا — على نمط io/export.js (lossOf).
    الأعمدة/الأدوات/الدرج تدخل الحساب نفسه (المراجعة #5) — B قد
    تصل من مستدعٍ قديمٍ بلا هذه الحقول (اختبارٌ يبني B يدوياً)،
    فـ||{} يُبقي الحساب سليماً بصفرٍ لا استثناء. */
 const C=B.cols||{hidden:0,noplot:0,n:0}, F=B.fixt||{hidden:0,noplot:0,n:0},
  T=B.stairs||{hidden:0,noplot:0,n:0};
 const hid=B.walls.hidden+B.opens.hidden+B.areas.hidden
  +C.hidden+F.hidden+T.hidden;
 const nop=B.walls.noplot+B.opens.noplot+B.areas.noplot
  +C.noplot+F.noplot+T.noplot;
 if(hid)
  n.push(`${hid} عنصراً على طبقةٍ مخفيّة استُبعد من الجدول — `
   +`الإخفاء عرضٌ لا حذف`);
 if(nop)
  n.push(`${nop} عنصراً على طبقةٍ تُرى ولا تُطبَع استُبعد من الجدول`);
 if(!B.areas.n&&!B.walls.n&&!B.opens.total&&!C.n&&!F.n&&!T.n&&!hid&&!nop)
  n.push("المشروع فارغ");
 return n;
}
/* اسمُ الملفّ من اسم المشروع — بلا محارف تُعطِب مساراً */
export const csvName=B=>String(B.name||"PLAN")
 .replace(/[\\/:*?"<>|]+/g,"_").slice(0,40).trim()
 .replace(/\s+/g,"_")+"-BOQ.csv";
