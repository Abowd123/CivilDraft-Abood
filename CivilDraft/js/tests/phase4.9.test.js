/* ═══ دفعة 4.9 — اختبار BOQ (السيناريوهات السبعة) ═══
   node js/tests/phase4.9.test.js

   البند التاسع من خطة المرحلة 4: كامل المشروع · مشروعٌ مع طبقاتٍ
   مخفيّة (تُستبعَد) · مشروعٌ مع طبقاتٍ مقفلة (تدخل — بخلاف
   المخفيّة) · مشروعٌ مع طبقاتٍ غير قابلةٍ للطباعة (تُستبعَد
   كالمخفيّة، بعلمٍ مختلف) · مشروعٌ مع فتحاتٍ معطوبة (over/clash/
   orphan) · مشروعٌ مع مناطق قديمة (stale، بعد تغيير جدارٍ حقيقي
   لا بصمةٍ مزيَّفة) · والتأكّد أن النطاق الفعلي يطابق ما وُثّق في
   README.

   والفارق عن js/tests/boq.test.js (الاختبار العامّ الموجود سلفاً):
   ذاك يفحص كل قسمٍ (مناطق/فتحات/جدران) بحالاتٍ مبعثرة — القفل على
   المناطق وحدها، والإخفاء وعدم الطباعة على قسمٍ واحدٍ في كل
   مجموعة، والمعطوبة over/orphan بلا clash، والقديمة ببصمةٍ مزيَّفة
   مباشرةً على a.stamp لا بتعديل جدارٍ فعليّ. هذا الملفّ يسدّ ذلك:
   الثلاثة الأقسام معاً تحت الحالة نفسها في كل مجموعة (فلا فجوةٌ
   ممكنة بين وحدةٍ فُحصت ووحدةٍ افتُرض تعميم حكمها عليها)، وحالات
   الفتحة الأربع كلّها في مشروعٍ واحد، والقديمة عبر applyOne على
   سماكة جدارٍ حيّ فيتغيّر stampOf فعلاً — لا حقنٌ مباشر.

   ═══ التدقيق ═══ areaRows/openRows/wallRows الثلاثة تُبنى على
   الحارس الواحد نفسه inScope=L=>vis(L)&&plots(L) (boq.js) — فلا
   مجالَ نظريّاً لانحرافٍ بين قسمٍ وآخر. والتحقّق هنا عمليٌّ لا
   نظريّ: يُشغِّل الحالة نفسها (إخفاء/عدم طباعة/قفل) على الأقسام
   الثلاثة معاً في نفس المشروع ويقارن الأعداد. لم يظهر انحرافٌ —
   لا عيبَ مرقَّماً، سدُّ فجوة اختبارٍ فقط، كأخواتها 4.4/4.7/4.8. */
import {shim,group,ok,eq,summary} from "./harness.js";
shim();
import {readFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {join} from "node:path";

const {S,newState,ensureShape}=await import("../core/state.js");
const {addWall}=await import("../core/walls.js");
const {addOpen}=await import("../core/opens.js");
const {addArea,isStale}=await import("../core/areas.js");
const {boq,boqLine,areaRows,openRows,wallRows}
 =await import("../core/boq.js");
const {setLay}=await import("../core/layers.js");
const {applyOne}=await import("../core/batch.js");
const {noteOf,toCSV}=await import("../io/boq.js");

const reset=()=>{newState(); S.meta.name="T"; S.meta.wallH=3000};

/* مشروعٌ صغيرٌ بالأقسام الثلاثة معاً: جدارٌ خارجيّ وسترة (طبقتا
   جدرانٍ مختلفتان)، بابٌ وشباك (طبقتا فتحاتٍ مختلفتان)، ومنطقةٌ
   واحدة — يكفي هذا لفحص كل قسمٍ على حدة بلا تضخيمٍ لا لزوم له. */
function build(){
 reset();
 const w=addWall([0,0],[4000,0],200,"int","c");
 addWall([0,3000],[2000,3000],200,"low","c",1000);
 addOpen(w,1000,"door",900,2100,0);
 addOpen(w,3000,"window",600,1400,900);
 addArea([[0,0],[4000,0],[4000,2000],[0,2000]],"غرفة");
 ensureShape();
}

/* ═══ 1 · كامل المشروع — الأقسام الثلاثة تحسب النطاق الافتراضي
   معاً، بلا استبعادٍ ولا معطوبٍ ولا قديم ═══ */
group("[4.9] كامل المشروع — الأقسام الثلاثة داخل النطاق الافتراضي",()=>{
 build();
 const B=boq();
 eq(B.walls.n,2,"جداران (داخليّ وسترة)");
 eq(B.opens.total,2,"فتحتان (باب وشباك)");
 eq(B.areas.n,1,"منطقةٌ واحدة");
 eq(B.walls.hidden+B.walls.noplot,0,"لا استبعاد جدرانٍ");
 eq(B.opens.hidden+B.opens.noplot,0,"لا استبعاد فتحاتٍ");
 eq(B.areas.hidden+B.areas.noplot,0,"لا استبعاد مناطق");
 eq(B.opens.bad,0,"لا فتحةٍ معطوبة");
 eq(B.areas.stale,0,"لا منطقةٍ قديمة");
});

/* ═══ 2 · طبقاتٌ مخفيّة معاً: الأقسام الثلاثة تستبعد وتُحصي
   بنفس القاعدة ═══ */
group("[4.9] طبقاتٌ مخفيّة — تُستبعَد من الأقسام الثلاثة معاً وتُحصى",()=>{
 build();
 setLay("A-WALL-LOW","off",1);   /* السترة وحدها */
 setLay("A-DOOR","off",1);       /* الباب وحده */
 setLay("A-AREA","off",1);       /* المنطقة */
 const W=wallRows(), O=openRows(), A=areaRows();
 eq(W.n,1,"جدارٌ واحدٌ بقي (الداخليّ) — السترة مخفيّة");
 eq(W.hidden,1,"وسترةٌ واحدةٌ مخفيّة");
 eq(O.total,1,"فتحةٌ واحدة بقيت (الشباك) — الباب مخفيّ");
 eq(O.hidden,1,"وبابٌ واحد مخفيّ");
 eq(A.n,0,"لا منطقة — كلّها على الطبقة المخفيّة");
 eq(A.hidden,1,"ومنطقةٌ واحدةٌ مخفيّة لا معدومة");
 /* noteOf تجمع مخفيّ الأقسام الثلاثة في ملاحظةٍ واحدة بعددٍ
    إجماليّ (hid=walls.hidden+opens.hidden+areas.hidden في
    io/boq.js) — لا ثلاث ملاحظاتٍ منفصلة؛ فالعدد هو ما يُثبَت هنا */
 const N=noteOf(boq());
 eq(N.filter(s=>/مخفيّة/.test(s)).length,1,
  "ملاحظةٌ واحدة مجمَّعة — لا ثلاثٌ منفصلة بالقسم");
 ok(N.some(s=>/مخفيّة/.test(s)&&/3\s+عنصر/.test(s)),
  "وتذكر العدد الإجماليّ الصحيح: ثلاثة عناصر (سترة+باب+منطقة)");
});

/* ═══ 3 · طبقاتٌ غير قابلةٍ للطباعة: نفس الاستبعاد بعلمٍ مختلف
   (plots=0 لا vis=off) — الأقسام الثلاثة معاً ═══ */
group("[4.9] طبقاتٌ غير قابلةٍ للطباعة — الأقسام الثلاثة تستبعد بعلم plots",
 ()=>{
 build();
 setLay("A-WALL-LOW","plot",0);
 setLay("A-DOOR","plot",0);
 setLay("A-AREA","plot",0);
 const W=wallRows(), O=openRows(), A=areaRows();
 eq(W.n,1,"السترة استُبعدت بعدم الطباعة لا بالإخفاء");
 eq(W.hidden,0,"وليست ضمن المخفيّ"); eq(W.noplot,1,"بل ضمن غير القابل للطباعة");
 eq(O.total,1,"الباب استُبعد كذلك");
 eq(O.hidden,0,"ليس مخفيّاً"); eq(O.noplot,1,"غير قابلٍ للطباعة");
 eq(A.n,0,"المنطقة استُبعدت أيضاً");
 eq(A.hidden,0,"ليست مخفيّة"); eq(A.noplot,1,"غير قابلةٍ للطباعة");
});

/* ═══ 4 · القفل لا يستبعد من أيّ قسمٍ من الثلاثة — كلّها تبقى
   داخل الجدول رغم القفل المتزامن ═══ */
group("[4.9] القفل لا يستبعد — الأقسام الثلاثة تبقى كاملةً رغم القفل",()=>{
 build();
 setLay("A-WALL","lk",1);
 setLay("A-GLAZ","lk",1);
 setLay("A-AREA","lk",1);
 const W=wallRows(), O=openRows(), A=areaRows();
 eq(W.n,2,"الجدران الاثنان باقيان");
 eq(O.total,2,"الفتحتان باقيتان");
 eq(A.n,1,"المنطقة باقية");
 eq(W.hidden+W.noplot+O.hidden+O.noplot+A.hidden+A.noplot,0,
  "لا استبعاد من أيّ قسمٍ — القفل يمنع اللمس لا الحضور في الجدول");
});

/* ═══ 5 · فتحاتٌ معطوبة: الحالات الأربع (ok/over/clash/orphan) في
   مشروعٍ واحد — كلّها تبقى داخل BOQ وتُحصى صراحةً، لا حذف صامت
   لأيٍّ منها ═══ */
group("[4.9] فتحاتٌ معطوبة — over وclash وorphan تبقى وتُحصى معاً",()=>{
 reset();
 /* بابٌ سليم على جدارٍ مستقلّ — ضابطٌ (control) لا يتأثّر */
 const wOk=addWall([0,0],[4000,0],200,"int","c");
 addOpen(wOk,1000,"door",900,2100,0);
 /* بابٌ آخر يُخرَج عن مدى جدارِه بعد التركيب — over */
 const wOver=addWall([0,2000],[4000,2000],200,"int","c");
 const dOver=addOpen(wOver,1000,"door",900,2100,0);
 /* شباكان متباعدان عند الإنشاء (addOpen يرفض التراكب) ثم يُقرَّبان
    بعده مباشرةً — clash */
 const wClash=addWall([0,4000],[4000,4000],200,"int","c");
 const w1=addOpen(wClash,1000,"window",600,1400,900);
 const w2=addOpen(wClash,2500,"window",600,1400,900);
 /* شباكٌ ثالث يُنسَب لاحقاً إلى جدارٍ لا وجود له — orphan */
 const wOrphan=addWall([0,6000],[4000,6000],200,"int","c");
 const wO=addOpen(wOrphan,1000,"window",600,1400,900);
 ensureShape();

 eq(openRows().bad,0,"لا معطوبة عند التركيب — شرطٌ مسبق");
 dOver.s=3900;            /* يخرج عن مدى الجدار (٤٠٠٠) */
 w2.s=w1.s;               /* يتراكب مع w1 الآن */
 wO.wall="ZZZZ";          /* جدارٌ لا وجود له */

 const O=openRows();
 eq(O.total,5,"الفتحاتُ الخمس كلّها تبقى — لا حذف صامت لمعطوبة");
 eq(O.bad,4,"أربعٌ معطوبة: over واحدة، clash اثنتان، orphan واحدة");

 const doorRow=O.rows.find(r=>r.kind==="door");
 const winRow=O.rows.find(r=>r.kind==="window");
 eq(doorRow.n,2,"بابان — السليم والمعطوب");
 eq(doorRow.bad,1,"واحدٌ منهما معطوبٌ فقط");
 eq(winRow.n,3,"ثلاثة شبابيك — تصادمٌ اثنان ويتيمةٌ واحدة");
 eq(winRow.bad,3,"الثلاثة معطوبةٌ معاً — لا سليم بينها");

 const B=boq();
 ok(/4 معطوبة/.test(boqLine(B)),"سطر الحصيلة يذكر الأربع معاً");
 ok(noteOf(B).some(s=>/4 فتحةً معطوبة/.test(s)),
  "والملاحظات تجمع الأربع في عددٍ واحد — لا عدٌّ منفصلٌ بالحالة");
});

/* ═══ 5ب · الحدّ الفاصل بين «متصادمان» و«متجاوران» (G9-7-12) ═══
   شباكان متلاصقان تماماً (نهاية الأوّل = بداية الثاني) سليمان. وopens.js
   يتسامح بمليمترٍ واحد (a<d-1) فالتراكب 1مم لا يُعدّ تصادماً، و2مم يُعدّ. */
group("[4.9] شباكان متجاوران تماماً سليمان، وتراكب 2مم يصادم",()=>{
 reset();
 const w=addWall([0,0],[6000,0],200,"int","c");
 const a=addOpen(w,1000,"window",600,1400,900);
 const b=addOpen(w,2500,"window",600,1400,900);
 ensureShape();
 b.s=a.s+a.w;                       /* متلاصقان: لا فراغ ولا تراكب */
 eq(openRows().bad,0,"متجاوران تماماً (s2=s1+w1): لا معطوبة");
 b.s=a.s+a.w-1;                     /* تراكب 1مم: ضمن تسامح opens.js */
 eq(openRows().bad,0,"تراكب 1مم ضمن التسامح المقصود: لا معطوبة");
 b.s=a.s+a.w-2;                     /* تراكب 2مم */
 ok(openRows().bad>=1,"تراكب 2مم: معطوبٌ (clash)");
});

/* ═══ G9-7-09: pan (عدد المصاريع) يُجمَع في BOQ للأنواع التي تقبله فقط ═══ */
group("[4.9] pan في BOQ: مصاريع لا صفوف، ولا تُحصى للكوّة والباب",()=>{
 reset();
 const w=addWall([0,0],[8000,0],200,"int","c");
 const win=addOpen(w,1000,"window",1200,1400,900);
 addOpen(w,3000,"door",900,2100,0);
 addOpen(w,5000,"niche",600,1200,900,{dep:100,face:"l"});
 ensureShape();
 const base=openRows();
 win.pan=3;
 const O=openRows();
 const wr=O.rows.find(r=>r.kind==="window");
 eq(wr.n,1,"صفٌّ/عددٌ واحد للشباك رغم 3 مصاريع");
 eq(wr.pan,3,"وpan=3 مجموع المصاريع");
 eq(O.rows.find(r=>r.kind==="door").pan||0,0,"الباب المفرد لا يُحصي مصاريع");
 eq(O.rows.find(r=>r.kind==="niche").pan||0,0,"والكوّة لا تُحصي مصاريع");
 eq(O.total,base.total,"وتغيير pan لا يزيد عدد الفتحات");
});

/* ═══ 6 · منطقةٌ قديمة عبر تغيير جدارٍ حقيقيّ (applyOne على
   السماكة) — لا بصمةٍ مزيَّفةٍ مباشرةً على a.stamp كما في
   boq.test.js. البصمة (stampOf) تعتمد سماكة الجدران المجاورة، فتغيّرُها
   الفعليّ هو ما يُفترَض أن يُقدِّم VER.g ويُخالِف البصمة القديمة ═══ */
group("[4.9] منطقةٌ قديمة عبر تعديل سماكة جدارٍ مجاورٍ فعلياً",()=>{
 reset();
 const w=addWall([0,0],[4000,0],200,"int","c");
 const a=addArea([[0,0],[4000,0],[4000,2000],[0,2000]],"غرفة");
 ensureShape();
 ok(!isStale(a),"سليمةٌ قبل أيّ تعديل");
 eq(areaRows().stale,0,"وBOQ يوافق ذلك");

 const r=applyOne({k:"wall",id:w.id},"t",0.3);   /* ٢٠٠ ← ٣٠٠ مم */
 ok(r.ok,"applyOne يقبل تعديل السماكة");
 eq(w.t,300,"السماكة تغيّرت فعلياً على الجدار الحيّ");
 ok(isStale(a),"المنطقة قديمةٌ الآن — بصمتها لم تعد تطابق الجوار");

 const A=areaRows();
 eq(A.n,1,"المنطقة تبقى داخل الجدول — لم تُحذَف");
 eq(A.stale,1,"وتُحصى قديمةً واحدة");
 eq(A.rows[0].stale,1,"وصفّها نفسه يحمل العلامة");
 eq(A.total,8000000,"والمساحة لم تُخصَم — القديمة تدخل بعلامةٍ لا حذف");
 const B=boq();
 ok(/1 قديمة/.test(boqLine(B)),"سطر الحصيلة يذكرها");
 ok(noteOf(B).some(s=>/قديمة/.test(s)),"والملاحظات تشرح السبب");
 ok(/قديمة/.test(toCSV(B).txt),"والعلامة تصل إلى CSV المُصدَّر");
});

/* ═══ 7 · النطاق الفعليّ يطابق ما وُثّق في README حرفياً — فحصٌ
   مباشرٌ لا استدلال: يقرأ README.md نفسه ويقارن جُمَله بسلوك BOQ
   الحيّ في سيناريوٍ واحدٍ يجمع كل شيء (مخفيّ + غير قابلٍ للطباعة +
   مقفل + معطوبة + قديمة معاً) ═══ */
group("[4.9] النطاق الفعليّ يطابق العقد الموثَّق في README.md",()=>{
 const here=fileURLToPath(new URL(".",import.meta.url));
 const readme=readFileSync(join(here,"..","..","README.md"),"utf8");
 /* الوثيقة تُلَفّ عند نحو ٧٠ حرفاً، فجملةٌ واحدة قد تقع على سطرين
    — تُطبَّع المسافات (بما فيها الأسطر) إلى فراغٍ واحد قبل المطابقة
    الحرفية، فلا يُخطئ التفافُ السطر مطابقةً حقيقية */
 const flat=readme.replace(/\s+/g," ");

 /* الجُمل الأربع التي يقوم عليها نطاق BOQ — موجودةٌ حرفياً */
 ok(flat.includes("**العناصر القابلة للطباعة** فقط"),
  "الوثيقة تنصّ: النطاق هو القابل للطباعة فقط");
 ok(flat.includes("مرئيةٌ (`vis`) وقابلةٌ للطباعة (`plots`) معاً"),
  "الوثيقة تنصّ: الشرط اجتماع vis وplots معاً");
 ok(flat.includes("المخفيّ وما على طبقةٍ تُرى ولا تُطبَع يُستبعَدان"),
  "الوثيقة تنصّ: المخفيّ وغير القابل للطباعة يُستبعَدان");
 ok(flat.includes("القفل لا يستبعد"),
  "الوثيقة تنصّ: القفل لا يستبعد");

 /* والسلوك الحيّ: كل بندٍ من الأربعة مجتمعاً في مشروعٍ واحد */
 build();
 setLay("A-WALL-LOW","off",1);     /* مخفيّة */
 setLay("A-DOOR","plot",0);        /* غير قابلةٍ للطباعة */
 setLay("A-AREA","lk",1);          /* مقفلة — لا تُستبعَد */
 const B=boq();
 eq(B.walls.n,1,"مطابقٌ: السترة المخفيّة استُبعدت");
 eq(B.opens.total,1,"مطابقٌ: البابُ غير القابل للطباعة استُبعد");
 eq(B.areas.n,1,"مطابقٌ: المنطقة المقفلة لم تُستبعَد");
 const s=boqLine(B);
 ok(/خارج الطباعة/.test(s),
  "سطر الحصيلة يذكر المستبعَد إجمالاً — كما تصف README «تُذكَر لا تختفي»");
});

process.exit(summary()?1:0);
