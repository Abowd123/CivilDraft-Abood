/* صندوق الجدران المحفوظة — لتمارين المستقيم والمستطيل */
const wallsBBox = S => {
  let x0 = 1 / 0, y0 = 1 / 0, x1 = -1 / 0, y1 = -1 / 0;
  (S.walls || []).forEach(w => {
    [w.a, w.b].forEach(p => {
      if (p[0] < x0) x0 = p[0]; if (p[0] > x1) x1 = p[0];
      if (p[1] < y0) y0 = p[1]; if (p[1] > y1) y1 = p[1];
    });
  });
  return (x1 < 0) ? null : { x0, y0, x1, y1 };
};

/* قاعدة فتحات: جدارٌ مستقيم بسماكة ٠٫١٥ م يُبنى كنصٍّ صريحٍ قبل
   الدرس، لأن أداة الفتحة تحتاج جداراً قائماً (خطوة ent:"wall"). */
const wallFix = (b, L = 6000) => {
  b.walls.push({ id: "W1", a: [0, 0], b: [L, 0], t: 150, type: "int", align: "c", level: 0 });
  return b;
};


